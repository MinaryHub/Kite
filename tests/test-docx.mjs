import { load, readSample } from './harness.mjs';
import fs from 'node:fs';
import JSZip from 'jszip';
const m = await load('tests/formats.entry.ts');
const count = (d) => { const c = {}; const walk = (n) => { c[n.type] = (c[n.type] || 0) + 1; (n.content || []).forEach(walk); }; walk(d.content); return c; };
const txt = (n) => n.type === 'text' ? n.text : (n.content || []).map(txt).join('');
const show = (doc, k = 15) => { for (const b of doc.content.content.slice(0, k)) console.log(' ', b.type, JSON.stringify(b.attrs || {}).slice(0, 120), '::', txt(b).slice(0, 80)); };
const validate = async (bytes, label) => { const zip = await JSZip.loadAsync(bytes); for (const n of Object.keys(zip.files)) { if (!/\.(xml|rels)$/.test(n)) continue; const d = new DOMParser().parseFromString(await zip.file(n).async('string'), 'application/xml'); if (d.getElementsByTagName('parsererror').length) console.log('XML ERROR', label, n); } };
const file = process.argv[2];
const r = file.endsWith('.docx') ? m.readDocx : file.endsWith('.hwp') ? m.readHwp : m.readHwpx;
const doc = await r(readSample(file));
console.log('READ', file, JSON.stringify(count(doc)), JSON.stringify(doc.settings.page), 'hdr', JSON.stringify(doc.settings.header), 'ftr', JSON.stringify(doc.settings.footer), JSON.stringify(doc.settings.pageNumber));
show(doc, +process.argv[3] || 12);
const out = await m.writeDocx(doc);
await validate(out, 'docx');
fs.writeFileSync('tests/.build/out-' + file.replace(/\.\w+$/, '') + '.docx', out);
const back = await m.readDocx(out);
console.log('DOCX BACK', JSON.stringify(count(back)), 'text same:', txt(doc.content) === txt(back.content), txt(doc.content).length, txt(back.content).length);
console.log('page', JSON.stringify(back.settings.page));
show(back, 6);
