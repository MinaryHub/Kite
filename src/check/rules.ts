/** '-ㄹ께/-ㄹ껄/-ㄹ꺼' → '-ㄹ게/-ㄹ걸/-ㄹ거' (받침 ㄹ 뒤의 된소리 표기) */
function rieulTense(m: RegExpExecArray): string | null {
  const prev = m[1];
  if (jong(prev) !== 8) return null;
  const map: Record<string, string> = { 께: '게', 껄: '걸', 꺼: '거' };
  return prev + map[m[2]];
}

// ---------------- 띄어쓰기 ----------------
/** 받침 ㄹ 음절 뒤의 의존 명사 붙여 쓰기: 할수있다 → 할 수 있다, 할것 → 할 것, 갈때 → 갈 때 */
function rieulDependent(m: RegExpExecArray): string | null {
  if (jong(m[1]) !== 8) return null;
  return `${m[1]} ${m[2]}${m[3] ? ' ' + m[3] : ''}`;
}

